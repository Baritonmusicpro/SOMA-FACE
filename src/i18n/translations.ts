export function formatCurrencyAmount(usdAmount: number, currency: CurrencyCode): string {
  const cfg = CURRENCY_CONFIG[currency];
  const converted = Math.round(usdAmount * cfg.rateFromUsd);
  return `${cfg.symbol}${converted.toLocaleString('en-US')}`;
}

export function formatProductVolume(
  volumeMetric: string,
  volumeImperial: string,
  system: VolumeSystem
): string {
  return system === 'imperial' ? volumeImperial : volumeMetric;
}
